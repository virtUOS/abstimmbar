"""Shared core of the question import (#323): result type, text helpers, limits.

Texts are never shortened or rephrased: whatever exceeds a limit is skipped
and reported instead.
"""
from __future__ import annotations

import html as html_lib
import re
from collections.abc import Callable
from dataclasses import dataclass, field

from django.conf import settings
from django.utils.translation import gettext
from lxml import etree

from rooms.sanitize import clean_html

FORMATS = ("simple", "gift", "h5p", "ilias")

MAX_QUESTIONS = 200
MAX_OPTIONS = 20
IMAGE_ALT_MAX = 300  # AnswerOption.image_alt
OPTION_TEXT_MAX = 500
QUESTION_TEXT_MAX = 10_000
# Internal draft marker set by ImportResult.add, removed again by finalize.
IMAGE_FLAG = "_image_dropped"
# Images kept from H5P/ILIAS packages (#336) travel beside the drafts; the
# draft HTML / option ``image`` carries this placeholder src until the view
# stores the image and swaps in its /media/ URL. Passes clean_html/clean_media_url.
IMPORT_IMAGE_PREFIX = "/media/_import/"
MAX_IMPORT_IMAGES = 100


@dataclass
class ImportImage:
    data: bytes
    filename: str  # short ASCII name generated by the reader
    alt: str = ""
    credit: dict = field(default_factory=dict)  # keys as the JSON transfer ``credit``


@dataclass
class ImportResult:
    format: str
    drafts: list[dict] = field(default_factory=list)
    skipped: dict[tuple[str, str], int] = field(default_factory=dict)
    # placeholder src -> image, in order of first reference
    images: dict[str, ImportImage] = field(default_factory=dict)
    _image_keys: dict[str, str] = field(default_factory=dict, repr=False)
    # Indices (into the finalized drafts) of drafts whose dropped image is
    # already reported, so storing the images counts a draft at most once.
    image_reported: set[int] = field(default_factory=set, repr=False)

    def images_full(self) -> bool:
        return len(self.images) >= MAX_IMPORT_IMAGES

    def add_image(self, img: ImportImage, key: str | None = None) -> str:
        """Register an image and return its placeholder src.

        ``key`` (the path inside the package) dedupes: the same file referenced
        twice yields the same placeholder. Beyond MAX_IMPORT_IMAGES it returns
        ``""``; the caller then treats the image as dropped and reports it via
        ``add(draft, image_dropped=True)``, so it counts only for kept questions.
        """
        if key is not None and key in self._image_keys:
            return self._image_keys[key]
        if self.images_full():
            return ""
        src = f"{IMPORT_IMAGE_PREFIX}{len(self.images) + 1}"
        self.images[src] = img
        if key is not None:
            self._image_keys[key] = src
        return src

    def skip(self, reason: str, detail: str = "", n: int = 1) -> None:
        key = (reason, detail)
        self.skipped[key] = self.skipped.get(key, 0) + n

    def add(self, draft: dict, image_dropped: bool = False) -> None:
        """Append a draft; an image dropped from it is reported only now, so a
        question skipped earlier never counts as "image not imported"."""
        if image_dropped:
            draft[IMAGE_FLAG] = True
            self.skip("image_dropped")
        self.drafts.append(draft)

    def _unskip(self, reason: str) -> None:
        key = (reason, "")
        if self.skipped.get(key, 0) > 1:
            self.skipped[key] -= 1
        else:
            self.skipped.pop(key, None)

    def skipped_list(self) -> list[dict]:
        return [
            {"reason": r, "detail": d, "count": c}
            for (r, d), c in sorted(self.skipped.items())
        ]


class ImportFailed(Exception):
    """File/text not readable -> 400 with str(exc) as message."""


def scrub_text(text: str) -> str:
    """Drop NUL and replace lone surrogates: PostgreSQL rejects NUL in text and
    JSON, and neither the sanitizer nor UTF-8 encoding accept surrogates."""
    return text.replace("\x00", "").encode("utf-8", "replace").decode("utf-8")


def html_paragraphs(text: str) -> str:
    """Escape plain text; blank lines become paragraphs, newlines ``<br>``."""
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
    paragraphs = [p for p in re.split(r"\n\s*\n", text) if p.strip()]
    return "".join(
        "<p>" + "<br>".join(html_lib.escape(ln.strip()) for ln in p.strip().split("\n")) + "</p>"
        for p in paragraphs
    )


_TAG_RE = re.compile(r"<[^>]*>")
_IMG_RE = re.compile(r"<img\b[^>]*>", re.IGNORECASE)


def _sub_tags(pattern: re.Pattern, s: str) -> str:
    """``pattern.sub("", s)`` in linear time for ``<...[^>]*>`` patterns.

    A ``<`` without any later ``>`` makes ``[^>]*`` scan to the end of the
    string on every attempt (quadratic on e.g. 40 000 ``<``). Behind the last
    ``>`` nothing can match, so only the part up to it is searched; the result
    is identical.
    """
    cut = s.rfind(">") + 1
    return pattern.sub("", s[:cut]) + s[cut:]


def has_image(html: str) -> bool:
    html = html or ""
    return bool(_IMG_RE.search(html, 0, html.rfind(">") + 1))


def strip_images(html: str) -> str:
    return _sub_tags(_IMG_RE, html or "")


def clean_without_images(raw: str) -> tuple[str, bool]:
    """Sanitize HTML without images; returns (html, an image was dropped).

    Strips again after sanitizing because the sanitizer allows ``img`` and
    normalizes tricks like ``<im<img>g`` or ``<image>`` into one.
    """
    raw = raw or ""
    stripped = strip_images(raw)
    html = clean_html(stripped)
    cleaned = strip_images(html)
    return cleaned.strip(), stripped != raw or cleaned != html


_SRC_RE = re.compile(r"""\bsrc\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))""", re.IGNORECASE)
_ALT_RE = re.compile(r"""\balt\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))""", re.IGNORECASE)
_KEPT_SRC_RE = re.compile(r'\bsrc="([^"]*)"')


def _attr(pattern: re.Pattern, tag: str) -> str:
    m = pattern.search(tag)
    if not m:
        return ""
    return html_lib.unescape(next(g for g in m.groups() if g is not None))


def img_tag(src: str, alt: str = "") -> str:
    return f'<img src="{html_lib.escape(src)}" alt="{html_lib.escape(alt)}">'


_IMAGE_EXTENSIONS = {"png": "png", "jpg": "jpg", "jpeg": "jpg", "gif": "gif", "webp": "webp"}
_IMAGE_MIMES = {"image/png": "png", "image/jpeg": "jpg", "image/gif": "gif", "image/webp": "webp"}


def import_filename(name: str = "", mime: str = "") -> str:
    """Short ASCII file name for an imported image (the package's own names
    may be long or non-ASCII); the extension only if it is a known one."""
    ext = _IMAGE_EXTENSIONS.get((name or "").rsplit(".", 1)[-1].lower()) if "." in (name or "") else None
    ext = ext or _IMAGE_MIMES.get((mime or "").lower(), "img")
    return f"import.{ext}"


def is_package_path(src: str) -> bool:
    """A relative path inside the package (no scheme, no absolute path)."""
    return bool(src) and not src.startswith(("/", "\\")) and ":" not in src.split("/", 1)[0]


def image_srcs(html: str) -> list[str]:
    """``src`` of every ``<img>`` in sanitized HTML, in document order."""
    html = html or ""
    return [
        html_lib.unescape(m.group(1)) if (m := _KEPT_SRC_RE.search(tag)) else ""
        for tag in _IMG_RE.findall(html, 0, html.rfind(">") + 1)
    ]


def image_alts(html: str) -> list[str]:
    """``alt`` of every ``<img>`` in sanitized HTML, parallel to ``image_srcs``."""
    html = html or ""
    return [
        html_lib.unescape(_attr(_ALT_RE, tag)).strip()
        for tag in _IMG_RE.findall(html, 0, html.rfind(">") + 1)
    ]


def clean_keeping_images(raw: str, resolve: Callable[[str], str]) -> tuple[str, bool]:
    """Sanitize HTML keeping package images (#336); returns (html, an image was dropped).

    Every ``<img>`` tag is rebuilt as ``<img src=resolve(src) alt=...>``;
    ``resolve`` returns a placeholder src or ``""`` (image removed). After
    sanitizing, any image whose src ``resolve`` did not return in this call is
    removed too: tricks like ``<im<img>g src=...>`` only form an image later,
    and a package must not reference this instance's /media/ files directly.
    """
    raw = raw or ""
    kept: set[str] = set()
    dropped = False

    def rebuild(m: re.Match) -> str:
        nonlocal dropped
        tag = m.group(0)
        src = _attr(_SRC_RE, tag).strip()
        placeholder = resolve(src) if src else ""
        if not placeholder:
            dropped = True
            return ""
        kept.add(placeholder)
        return img_tag(placeholder, _attr(_ALT_RE, tag))

    cut = raw.rfind(">") + 1
    rebuilt = _IMG_RE.sub(rebuild, raw[:cut]) + raw[cut:]
    html = clean_html(rebuilt)

    def keep_known(m: re.Match) -> str:
        nonlocal dropped
        src = _KEPT_SRC_RE.search(m.group(0))
        if src and html_lib.unescape(src.group(1)) in kept:
            return m.group(0)
        dropped = True
        return ""

    cut = html.rfind(">") + 1
    cleaned = _IMG_RE.sub(keep_known, html[:cut]) + html[cut:]
    return cleaned.strip(), dropped


def plain(html_or_text: str) -> str:
    """Strip tags, resolve entities, trim whitespace."""
    return html_lib.unescape(_sub_tags(_TAG_RE, html_or_text or "")).strip()


def true_false_labels() -> tuple[str, str]:
    if getattr(settings, "CONTENT_DEFAULT_LANGUAGE", "de") == "en":
        return ("True", "False")
    return ("Wahr", "Falsch")


def finalize(result: ImportResult, allowed_kinds: tuple[str, ...]) -> ImportResult:
    """Apply limits; skipped questions are reported, texts are never altered."""
    kept: list[dict] = []
    for draft in result.drafts:
        image_dropped = draft.pop(IMAGE_FLAG, False)
        kept_before = len(kept)
        options = draft.get("options") or []
        if (
            draft["kind"] == "single_choice"
            and not draft.get("binary_choice")
            and sum(bool(o.get("is_correct")) for o in options) > 1
        ):
            # e.g. ILIAS single choice with several positive answers: the
            # editor only accepts that as multiple choice; texts stay verbatim.
            draft["kind"] = "multiple_choice"
        if draft["kind"] not in allowed_kinds:
            result.skip("not_allowed_in_set", draft["kind"])
        elif len(options) > MAX_OPTIONS:
            result.skip("too_many_options")
        elif any(len(o["text"]) > OPTION_TEXT_MAX for o in options):
            result.skip("option_too_long")
        elif len(draft["text"]) > QUESTION_TEXT_MAX:
            result.skip("text_too_long")
        else:
            kept.append(draft)
        if image_dropped and len(kept) == kept_before:
            result._unskip("image_dropped")  # question itself skipped
        elif image_dropped:
            draft[IMAGE_FLAG] = True
    if len(kept) > MAX_QUESTIONS:
        result.skip("over_limit", n=len(kept) - MAX_QUESTIONS)
        for draft in kept[MAX_QUESTIONS:]:
            if draft.get(IMAGE_FLAG):
                result._unskip("image_dropped")
        kept = kept[:MAX_QUESTIONS]
    result.image_reported = {i for i, draft in enumerate(kept) if draft.pop(IMAGE_FLAG, None)}
    result.drafts = kept
    return result


def safe_xml(data: bytes) -> etree._Element:
    """Parse untrusted XML: no DTD loading, no network, no entity expansion.

    Documents declaring entities (XXE, billion laughs) are rejected outright;
    an external-only DOCTYPE (as in every ILIAS export) is accepted.
    """
    parser = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False, load_dtd=False)
    try:
        root = etree.fromstring(data, parser)
    except (etree.LxmlError, ValueError, TypeError) as exc:
        raise ImportFailed(gettext("The file is not valid XML.")) from exc
    if root is None:
        raise ImportFailed(gettext("The file is not valid XML."))
    dtd = root.getroottree().docinfo.internalDTD
    has_entities = dtd is not None and any(True for _ in dtd.iterentities())
    if has_entities or any(isinstance(el, etree._Entity) for el in root.iter()):
        raise ImportFailed(gettext("The XML file declares entities, which are not allowed."))
    return root
